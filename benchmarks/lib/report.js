#!/usr/bin/env node
/**
 * Shared markdown report writer. Every generated report embeds the SAME
 * environment disclosure block and a note that the file was written by the
 * runner itself — never hand-edited — so numbers can't silently drift from
 * the code that produced them.
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { collectEnvInfo, envInfoSummary } = require('./env-info.js');

function writeReport(fileName, { title, summary, reproCommand, body }) {
  const envInfo = collectEnvInfo();
  const md = `# ${title}

> **Auto-generated by its runner script — do not hand-edit.** Regenerate with
> the command below; the numbers here are exactly what that command printed.

${summary}

---

## Environment

${envInfoSummary(envInfo)}

---

## Exact Reproduction Command

\`\`\`bash
${reproCommand}
\`\`\`

---

${body}

---

*Generated ${envInfo.capturedAt} at git commit \`${envInfo.git.commit}\`${envInfo.git.dirty ? ' (dirty working tree — re-run after committing for a citable result)' : ''}.*
`;
  const outPath = path.join(__dirname, '..', 'reports', fileName);
  fs.writeFileSync(outPath, md, 'utf8');
  console.log(`\n📄 Report written: benchmarks/reports/${fileName}`);
  return outPath;
}

module.exports = { writeReport };
